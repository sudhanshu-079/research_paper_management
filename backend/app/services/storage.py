"""Local file storage. Files live under UPLOAD_DIR/<owner_id>/<uuid>.pdf.

The filename on disk is always generated by us, never taken from the client,
which rules out path traversal.
"""
import uuid
from pathlib import Path

from app.config import settings


def _owner_dir(owner_id: str) -> Path:
    d = Path(settings.upload_dir) / owner_id
    d.mkdir(parents=True, exist_ok=True)
    return d


def save_pdf(owner_id: str, data: bytes) -> str:
    path = _owner_dir(owner_id) / f"{uuid.uuid4().hex}.pdf"
    path.write_bytes(data)
    return str(path)


def delete_file(path: str | None) -> None:
    if not path:
        return
    root = Path(settings.upload_dir).resolve()
    p = Path(path).resolve()
    if root in p.parents and p.exists():  # never delete outside the upload dir
        p.unlink()


def resolve_pdf_file(path: str | None) -> Path | None:
    if not path:
        return None
    root = Path(settings.upload_dir).resolve()
    pdf_path = Path(path).resolve()
    if root not in pdf_path.parents or not pdf_path.is_file():
        return None
    return pdf_path
